    /**
     * Daily automated job: runs at midnight every day.
     * Automatically scans published stories and generates a fresh Knowledge Keeper with Groq AI if none scheduled.
     */
    @Scheduled(cron = "0 0 0 * * ?")
    public void autoGenerateDailyKnowledgeKeeper() {
        LocalDate today = LocalDate.now();
        log.info("[KnowledgeKeeperService] Running daily midnight rotation check for {}", today);
        if (repository.findFirstByActiveDate(today).isEmpty()) {
            autoGenerateForDate(today);
        }
    }

    /**
     * Public Home Screen endpoint: Returns today's active Knowledge Keeper.
     * Guarantees:
     * - Exactly 1 knowledge keeper per day
     * - Changes daily at midnight
     * - Formed automatically from published stories with Groq AI or sequential rotation
     */
    @Transactional
    public FeaturedKeeperResponse getFeaturedKeeperOfToday() {
        LocalDate today = LocalDate.now();

        // 1. Look for a keeper scheduled as Active for today
        Optional<FeaturedKeeper> todayKeeper = repository.findByActiveDateAndStatus(today, "Active");
        if (todayKeeper.isPresent()) {
            return mapToResponse(todayKeeper.get());
        }

        // 2. Look for any keeper with today's active date
        Optional<FeaturedKeeper> scheduledToday = repository.findFirstByActiveDate(today);
        if (scheduledToday.isPresent()) {
            FeaturedKeeper keeper = scheduledToday.get();
            keeper.setStatus("Active");
            return mapToResponse(repository.save(keeper));
        }

        // 3. Try to auto-generate a fresh keeper from published stories for today
        FeaturedKeeper generated = autoGenerateForDate(today);
        if (generated != null) {
            return mapToResponse(generated);
        }

        // 4. Fallback: Deterministic daily rotation through all existing keepers
        List<FeaturedKeeper> all = repository.findAll(Sort.by("id"));
        if (!all.isEmpty()) {
            int dayIndex = (int) (Math.abs(today.toEpochDay()) % all.size());
            return mapToResponse(all.get(dayIndex));
        }

        throw new ResourceNotFoundException("No Knowledge Keeper found");
    }

    /**
     * Automatically picks a published story (preferring blogs) that has not yet been featured,
     * scans the content, calls Groq AI to extract an insightful quote and honorific title,
     * and sets it as the active Knowledge Keeper.
     */
    @Transactional
    public FeaturedKeeper autoGenerateForDate(LocalDate targetDate) {
        try {
            List<ModerationQueueItem> publishedStories = moderationQueueRepository.findByStatus(StoryStatus.PUBLISHED);
            if (publishedStories.isEmpty()) {
                // Also check approved stories
                publishedStories = moderationQueueRepository.findAll();
            }

            if (publishedStories.isEmpty()) {
                log.warn("[KnowledgeKeeperService] No published stories available to generate Knowledge Keeper");
                return null;
            }

            // Prefer blogs, but allow other story types
            List<ModerationQueueItem> eligible = publishedStories.stream()
                    .filter(s -> !repository.existsByStoryId(s.getId().toString()))
                    .sorted((a, b) -> {
                        int aWeight = "blog".equalsIgnoreCase(a.getType()) ? 1 : 0;
                        int bWeight = "blog".equalsIgnoreCase(b.getType()) ? 1 : 0;
                        return Integer.compare(bWeight, aWeight);
                    })
                    .collect(Collectors.toList());

            // If all published stories were already featured, reuse the oldest published story
            ModerationQueueItem chosenStory = !eligible.isEmpty() ? eligible.get(0) : publishedStories.get(0);

            return generateAndSaveKeeper(chosenStory, targetDate, "Active");
        } catch (Exception e) {
            log.error("[KnowledgeKeeperService] Error auto-generating Knowledge Keeper: {}", e.getMessage(), e);
            return null;
        }
    }

    /**
     * Manual generation by Admin using Groq AI from a specific story ID.
     */
    @Transactional
    public FeaturedKeeperResponse generateFromStoryId(UUID storyId, LocalDate activeDate) {
        ModerationQueueItem story = moderationQueueRepository.findById(storyId)
                .orElseThrow(() -> new ResourceNotFoundException("Story not found with ID: " + storyId));

        LocalDate targetDate = activeDate != null ? activeDate : LocalDate.now();
        FeaturedKeeper keeper = generateAndSaveKeeper(story, targetDate, "Scheduled");
        return mapToResponse(keeper);
    }

    private FeaturedKeeper generateAndSaveKeeper(ModerationQueueItem story, LocalDate targetDate, String status) {
        String authorName = resolveAuthorName(story);
        String avatarUrl = resolveAuthorAvatar(story);

        String title = story.getTitle();
        String description = story.getDescription();
        String body = story.getBodyContent();

        // 1. Ask Groq AI to extract key wisdom quote, title, and tag
        String rawGroq = groqAiService.generateKnowledgeKeeper(title, description, body, authorName);

        String quote = null;
        String keeperTitle = null;
        String tag = null;

        if (rawGroq != null && !rawGroq.isBlank()) {
            try {
                JsonNode root = objectMapper.readTree(rawGroq);
                if (root.has("quote") && !root.path("quote").asText().isBlank()) {
                    quote = root.path("quote").asText().trim();
                }
                if (root.has("title") && !root.path("title").asText().isBlank()) {
                    keeperTitle = root.path("title").asText().trim();
                }
                if (root.has("tag") && !root.path("tag").asText().isBlank()) {
                    tag = root.path("tag").asText().trim().toUpperCase();
                }
            } catch (Exception ex) {
                log.warn("[KnowledgeKeeperService] Failed to parse Groq response, applying fallback: {}", ex.getMessage());
            }
        }

        // 2. Intelligent fallback if AI was unavailable
        if (quote == null || quote.isBlank()) {
            quote = extractFallbackQuote(body, description, title);
        }
        if (keeperTitle == null || keeperTitle.isBlank()) {
            keeperTitle = "Traditional Knowledge Custodian";
        }
        if (tag == null || tag.isBlank()) {
            tag = "CULTURAL HERITAGE";
        }

        FeaturedKeeper keeper = new FeaturedKeeper();
        keeper.setName(authorName);
        keeper.setTitle(keeperTitle);
        keeper.setTag(tag);
        keeper.setQuote(quote);
        keeper.setAvatarUrl(avatarUrl);
        keeper.setStoryId(story.getId().toString());
        keeper.setStoryTitle(story.getTitle());
        keeper.setActiveDate(targetDate);
        keeper.setStatus(status);
        keeper.setGeneratedByAi(true);
        keeper.setLikesCount(story.getLikesCount() != null ? story.getLikesCount() : 0);

        FeaturedKeeper saved = repository.save(keeper);
        log.info("[KnowledgeKeeperService] Generated Knowledge Keeper '{}' for date {}", saved.getName(), targetDate);
        return saved;
    }

    private String extractFallbackQuote(String body, String description, String title) {
        String source = (body != null && !body.isBlank()) ? body : ((description != null && !description.isBlank()) ? description : title);
        if (source == null) return "Preserving Sri Lanka's living traditions for future generations.";

        // Split sentences by period
        String[] sentences = source.split("\\.");
        if (sentences.length > 0 && sentences[0].trim().length() > 20) {
            String q = sentences[0].trim();
            if (q.length() > 200) q = q.substring(0, 200) + "...";
            return q + ".";
        }
        return source.length() > 180 ? source.substring(0, 180) + "..." : source;
    }

    private String resolveAuthorName(ModerationQueueItem story) {
        if (story.getAuthor() != null && story.getAuthor().getFullName() != null && !story.getAuthor().getFullName().isBlank()) {
            return story.getAuthor().getFullName();
        }
        if (story.getAuthorName() != null && !story.getAuthorName().isBlank()) {
            return story.getAuthorName();
        }
        return "Traditional Knowledge Holder";
    }

    private String resolveAuthorAvatar(ModerationQueueItem story) {
        if (story.getAuthor() != null && story.getAuthor().getProfilePhotoUrl() != null && !story.getAuthor().getProfilePhotoUrl().isBlank()) {
            return story.getAuthor().getProfilePhotoUrl();
        }
        if (story.getImageUrl() != null && !story.getImageUrl().isBlank()) {
            return story.getImageUrl();
        }
        return "https://images.unsplash.com/photo-1544005313-94ddf0286df2?q=80&w=200";
    }

